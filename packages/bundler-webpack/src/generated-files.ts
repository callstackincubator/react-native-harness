import fs from 'node:fs';
import path from 'node:path';
import type { Config as HarnessConfig } from '@react-native-harness/config';

const RUNTIME_ENTRY = '@react-native-harness/runtime/webpack/entry-point';

export type GeneratedPaths = {
  dir: string;
  /** Sets the `RN_HARNESS` global and starts the runtime. Replaces the app entry. */
  entry: string;
  /** The test and setup files of the run, handed to the runtime by the entry. */
  testFiles: string;
};

/**
 * One directory per server, so that two runs in one project, on different
 * ports, do not write over each other's files. The files are `.cjs`, so that
 * the project's loaders skip them and its `"type"` does not decide how
 * webpack reads them.
 */
export const getGeneratedPaths = (
  projectRoot: string,
  port: number
): GeneratedPaths => {
  const dir = path.resolve(projectRoot, '.harness', 'webpack', String(port));

  return {
    dir,
    entry: path.join(dir, 'entry.cjs'),
    testFiles: path.join(dir, 'test-files.cjs'),
  };
};

/**
 * The module that replaces the app's entry. It does what Metro's manifest
 * polyfill does, then starts the runtime with the files of the run.
 */
export const renderEntryModule = (
  harnessConfig: Pick<
    HarnessConfig,
    'appRegistryComponentName' | 'disableViewFlattening'
  >
): string => `// Generated by React Native Harness. Do not edit.
globalThis.RN_HARNESS = {
  appRegistryComponentName: ${JSON.stringify(harnessConfig.appRegistryComponentName)},
  disableViewFlattening: ${String(harnessConfig.disableViewFlattening)},
};
require(${JSON.stringify(RUNTIME_ENTRY)}).start(require("./test-files.cjs").files);
`;

const toModuleRequest = (fromDir: string, file: string): string => {
  const relative = path.relative(fromDir, file).split(path.sep).join('/');

  return relative.startsWith('.') ? relative : `./${relative}`;
};

// A name for the file's chunk, which webpack and Rspack need to see both
// callbacks of `require.ensure`.
const toChunkName = (file: string): string =>
  `harness-${file.replace(/[^A-Za-z0-9_.-]/g, '_')}`;

/**
 * The module that maps each file the app may load to its module id and a
 * loader. `files` are relative to `projectRoot` and use `/`, as the runtime
 * receives them. They are listed once, in a stable order.
 *
 * `require.ensure` fetches a file's chunk without running the file, which the
 * runtime does later; the file's id comes from `require.resolveWeak`, so the
 * file does not join the chunk of this module. Its callbacks have to be
 * function expressions, and the chunk name a string, for the call to be seen.
 */
export const renderTestFilesModule = ({
  files,
  projectRoot,
  fromDir,
}: {
  files: readonly string[];
  projectRoot: string;
  fromDir: string;
}): string => {
  const entries = [...new Set(files)].sort().map((file) => {
    const request = JSON.stringify(
      toModuleRequest(fromDir, path.resolve(projectRoot, file))
    );
    const chunkName = JSON.stringify(toChunkName(file));

    return `  ${JSON.stringify(file)}: {
    id: require.resolveWeak(${request}),
    load: () =>
      new Promise((resolve, reject) => {
        require.ensure([${request}], () => resolve(), (error) => reject(error), ${chunkName});
      }),
  },`;
  });

  return `// Generated by React Native Harness. Do not edit.
exports.files = {
${entries.join('\n')}
};
`;
};

/** Writes `content` unless the file already has it. Returns whether it wrote. */
export const writeIfChanged = (filePath: string, content: string): boolean => {
  try {
    if (fs.readFileSync(filePath, 'utf8') === content) {
      return false;
    }
  } catch {
    // Not there yet.
  }

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);

  return true;
};
